export type SuperAdminMessageKey = keyof typeof en;

const catalogs: Record<SuperAdminLocale, Record<SuperAdminMessageKey, string>> = {
  en,
  el,
};

export function formatMessage(
  template: string,
  values?: MessageValues,
): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    values[key] != null ? String(values[key]) : `{${key}}`,
  );
}

export function getMessage(
  locale: SuperAdminLocale,
  key: SuperAdminMessageKey,
  values?: MessageValues,
): string {
  const template = catalogs[locale][key] ?? catalogs.en[key] ?? key;
  return formatMessage(template, values);
}

export function localeDateTimeString(
  locale: SuperAdminLocale,
  iso: string | null | undefined,
): string {
  if (!iso) return "—";
  return new Date(iso).toLocaleString(locale === "el" ? "el-GR" : "en-GB");
}

export function localeTimeString(
  locale: SuperAdminLocale,
  iso: string | null | undefined,
): string {
  if (!iso) return "—";
  return new Date(iso).toLocaleTimeString(locale === "el" ? "el-GR" : "en-GB");
}
